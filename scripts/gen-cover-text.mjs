// Generate outlined-text path data for the chan-cover preset.
//
// An SVG embedded via <img> on GitHub cannot load external fonts (Anton /
// DM Sans would fall back to a system face). So the brand text is converted
// to vector outlines here, baked into lib/presets/chanCoverText.js, and
// inlined by the preset. Re-run this if the wording or sizes change:
//   node scripts/gen-cover-text.mjs
//
// Fonts are vendored under assets/fonts/ (copied from the CV repo's cv/fonts).

import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const loadFont = (p) => {
  const buf = readFileSync(join(root, p));
  // Node Buffers share a pooled ArrayBuffer; slice to this file's bytes only.
  const ab = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
  return opentype.parse(ab);
};
const anton = loadFont('assets/fonts/Anton-Regular.ttf');
const dmsans = loadFont('assets/fonts/DMSans-Medium.ttf');

// Each line: baseline at y=0, left edge at x=0. The preset translates the
// resulting <path> group into place. We capture the advance width so the
// preset (and we) can verify the line fits the column / center it.
const lines = {
  name:        { font: anton,  size: 150, text: 'Chan Meng' },
  tagline:     { font: dmsans, size: 34,  text: '« Subtraction for life, addition for thought. »' },
  positioning: { font: dmsans, size: 22,  text: 'AI Agent Architect · Full-stack Engineer · AI-Tooling Expert' },
};

const out = {};
for (const [key, { font, size, text }] of Object.entries(lines)) {
  const path = font.getPath(text, 0, 0, size);
  const d = path.toPathData(2);
  const width = Math.round(font.getAdvanceWidth(text, size) * 100) / 100;
  out[key] = { d, width, size, text };
  console.log(`${key.padEnd(12)} size=${size}  width=${width.toFixed(1)}px  glyphs=${text.length}`);
}

const banner = `// AUTO-GENERATED by scripts/gen-cover-text.mjs — do not edit by hand.
// Outlined brand text (Anton + DM Sans) for the chan-cover preset, baked to
// vector paths so the cover renders identically as an <img> on GitHub (no
// external font fetch). Each entry: { d (baseline y=0, left x=0), width, size, text }.
`;
const body = `module.exports = ${JSON.stringify(out, null, 2)};\n`;
const dest = join(root, 'lib/presets/chanCoverText.js');
writeFileSync(dest, banner + body);
console.log(`\nOK wrote ${dest}`);

// ── Logo: extract the monkey+CHAN lockup paths + eye circles ────────────────
// Baked so the preset is self-contained (no cross-repo path at render time).
// Source: assets/chan-meng-logo-full.svg (chan-meng-logo full lockup, 0 0 276 356).
const logoSvg = readFileSync(join(root, 'assets/chan-meng-logo-full.svg'), 'utf8');
const paths = [...logoSvg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
const circles = [...logoSvg.matchAll(/<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"/g)]
  .map((m) => ({ cx: +m[1], cy: +m[2], r: +m[3] }));
// Order in the source: [head, mouth, CHAN wordmark]; two eye circles between.
if (paths.length !== 3 || circles.length !== 2) {
  throw new Error(`Unexpected logo structure: ${paths.length} paths, ${circles.length} circles`);
}
const logo = {
  viewBox: '0 0 276 356',
  head: paths[0],
  mouth: paths[1],
  wordmark: paths[2],
  eyes: circles,
};
const logoBanner = `// AUTO-GENERATED by scripts/gen-cover-text.mjs — do not edit by hand.
// Monkey+CHAN lockup paths (from chan-meng-logo full lockup, viewBox 0 0 276 356),
// baked for the chan-cover preset. head/mouth/wordmark = path d-strings; eyes =
// the two eye circles (wrapped in the blink group by the preset).
`;
const logoDest = join(root, 'lib/presets/chanCoverLogo.js');
writeFileSync(logoDest, logoBanner + `module.exports = ${JSON.stringify(logo, null, 2)};\n`);
console.log(`OK wrote ${logoDest} (${paths.length} paths, ${circles.length} eyes)`);
